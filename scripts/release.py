#!/usr/bin/env python3
"""HymnFlow release automation.

One command runs the whole sequence that used to be manual:

    python scripts/release.py 2.9.0              # bump -> build -> tag
    python scripts/release.py --minor            # auto-compute next version
    python scripts/release.py 2.9.0 --publish    # ... + push + GitHub release
    python scripts/release.py --rebuild          # rebuild artifacts for the
                                                 # current version, no bump/tag
    python scripts/release.py 2.9.0 --dry-run    # show the plan, change nothing

Steps (each gated by preflight checks):
  1. Preflight: clean tree, on master, tag free, JS syntax, data files
     present, CHANGELOG has a section for the new version.
  2. Bump the version in package.json, obs-dock/index.html,
     obs-dock/obs-dock.js and obs-setup.html (cache busters + badges).
  3. Require doc/RELEASE_NOTES_v<ver>.md (offers the changelog section as a
     starting point if missing).
  4. Commit the bump, build lite/full/data zips, verify their contents.
  5. Tag v<ver>.
  6. --publish: push master + tag, then create the GitHub release with the
     notes and all three zips. If the release already exists (e.g. it was
     pre-created in the web UI), its title/notes are corrected and the
     canonical assets uploaded alongside whatever is already attached.
"""

import argparse
import datetime as _dt
import json
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

# Windows consoles often default to cp1252, which can't print the status
# glyphs below — force UTF-8 (replacing anything truly unprintable).
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent

# ── What ships in each bundle ──────────────────────────────────────────────
PLUGIN_DIRS = ["public/obs-dock", "public/obs-overlay", "public/parsers", "public/i18n"]
PLUGIN_FILES = ["public/obs-setup.html", "public/validation.js"]
PLUGIN_DATA = ["public/data/bible-lookup.js", "public/data/hymns-data.js"]
PLUGIN_SCRIPTS = [
    "scripts/hymnflow-obs-hotkeys.py",
    "scripts/convert_bible_txt.py",
    "scripts/convert_yoruba_bible.py",
]
PLUGIN_DOCS = ["README.md", "doc/SETUP.md", "doc/TROUBLESHOOTING.md", "doc/SECURITY.md"]

# Bibles are large, git-ignored files — generated by scrape_bible_api.py or
# bundle_bible_kjv.py. The bible-en-* set is the accuracy-audited curated six.
BIBLES = [
    "public/data/bible-kjv.js",
    "public/data/en_bbe.json",
    "public/data/bible-yor.js",
    "public/data/bible-en-kjv.js",
    "public/data/bible-en-rv.js",
    "public/data/bible-en-lsv.js",
    "public/data/bible-en-gnv.js",
    "public/data/bible-en-dra.js",
    "public/data/bible-en-ojps.js",
]
HYMNS = [
    "hymn-bundle/cac_ghb.json",
    "hymn-bundle/cac_yhb.json",
    "hymn-bundle/fws.json",
    "hymn-bundle/nnbh.json",
    "hymn-bundle/umh.json",
    "hymn-bundle/ybh.json",
    "hymn-bundle/metadata.json",
]
LITE_EXTRAS = ["public/data/bible-kjv.js", "hymn-bundle/nnbh.json"]

# Files that carry the version string
VERSIONED_FILES = [
    "public/obs-dock/index.html",
    "public/obs-dock/obs-dock.js",
    "public/obs-setup.html",
]

JS_SYNTAX_CHECK = [
    "public/obs-dock/obs-dock.js",
    "public/obs-overlay/overlay.js",
    "public/data/bible-lookup.js",
    "public/i18n/i18n.js",
    "public/i18n/translations.js",
    "public/validation.js",
]


def run(cmd, check=True, capture=True, cwd=ROOT):
    r = subprocess.run(cmd, cwd=cwd, capture_output=capture, text=True,
                       encoding="utf-8", errors="replace")
    if check and r.returncode != 0:
        out = ((r.stdout or "") + (r.stderr or "")).strip()
        die(f"command failed: {' '.join(cmd)}\n{out}")
    return r


def die(msg):
    print(f"\n✖ {msg}", file=sys.stderr)
    sys.exit(1)


def step(msg):
    print(f"\n▶ {msg}")


def ok(msg):
    print(f"  ✓ {msg}")


def current_version():
    pkg = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    return pkg["version"]


def compute_version(args, cur):
    if args.version:
        if not re.fullmatch(r"\d+\.\d+\.\d+", args.version):
            die(f"version must look like X.Y.Z, got: {args.version}")
        return args.version
    major, minor, patch = map(int, cur.split("."))
    if args.major:
        return f"{major + 1}.0.0"
    if args.patch:
        return f"{major}.{minor}.{patch + 1}"
    return f"{major}.{minor + 1}.0"  # default: minor


# ── Preflight ──────────────────────────────────────────────────────────────

def preflight(new_ver, publish, rebuild):
    step("Preflight checks")

    branch = run(["git", "branch", "--show-current"]).stdout.strip()
    if branch != "master":
        die(f"not on master (on '{branch}') — release from master")
    ok("on master")

    if run(["git", "status", "--porcelain"]).stdout.strip():
        die("working tree is not clean — commit or stash first")
    ok("working tree clean")

    if not rebuild:
        tags = run(["git", "tag", "--list", f"v{new_ver}"]).stdout.strip()
        if tags:
            die(f"tag v{new_ver} already exists")
        ok(f"tag v{new_ver} is free")

    node = shutil.which("node")
    if not node:
        die("node not found on PATH (needed for JS syntax checks)")
    for f in JS_SYNTAX_CHECK:
        run([node, "--check", str(ROOT / f)])
    ok(f"JS syntax valid ({len(JS_SYNTAX_CHECK)} files)")

    missing = [f for f in BIBLES + HYMNS + PLUGIN_DATA + PLUGIN_DOCS if not (ROOT / f).exists()]
    if missing:
        die("bundle inputs missing (generate Bibles with scripts/scrape_bible_api.py):\n  "
            + "\n  ".join(missing))
    ok("all bundle inputs present")

    if not rebuild:
        changelog = (ROOT / "doc/CHANGELOG.md").read_text(encoding="utf-8")
        if f"## [{new_ver}]" not in changelog:
            die(f"doc/CHANGELOG.md has no '## [{new_ver}]' section — write it first")
        ok(f"CHANGELOG has a {new_ver} section")

        notes = ROOT / f"doc/RELEASE_NOTES_v{new_ver}.md"
        if not notes.exists():
            m = re.search(rf"## \[{re.escape(new_ver)}\].*?(?=\n## \[|\Z)", changelog, re.S)
            hint = "\nTip: start from the changelog section:\n\n" + m.group(0)[:400] + "…" if m else ""
            die(f"{notes.relative_to(ROOT)} not found — write the release notes first{hint}")
        ok(f"release notes present ({notes.name})")

    if publish:
        if not shutil.which("gh"):
            die("gh CLI not found — install it or drop --publish")
        r = run(["gh", "auth", "status"], check=False)
        if r.returncode != 0:
            die("gh is not authenticated — run: gh auth login")
        ok("gh authenticated")


# ── Version bump ───────────────────────────────────────────────────────────

def bump(old, new):
    step(f"Bumping {old} → {new}")
    today = _dt.date.today().isoformat()

    pkg_path = ROOT / "package.json"
    pkg_path.write_text(
        pkg_path.read_text(encoding="utf-8").replace(f'"version": "{old}"', f'"version": "{new}"'),
        encoding="utf-8")

    for rel in VERSIONED_FILES:
        p = ROOT / rel
        text = p.read_text(encoding="utf-8")
        text = text.replace(f"v={old}", f"v={new}")
        text = re.sub(rf"v{re.escape(old)} — \d{{4}}-\d{{2}}-\d{{2}}", f"v{new} — {today}", text)
        text = text.replace(f"Setup Guide v{old}", f"Setup Guide v{new}")
        text = text.replace(f"HymnFlow v{old}", f"HymnFlow v{new}")
        p.write_text(text, encoding="utf-8")

    stale = []
    for rel in ["package.json"] + VERSIONED_FILES:
        if old in (ROOT / rel).read_text(encoding="utf-8"):
            stale.append(rel)
    if stale:
        die(f"stale {old} references remain in: {', '.join(stale)}")
    ok(f"version strings updated in {1 + len(VERSIONED_FILES)} files, dated {today}")

    run(["git", "add", "package.json"] + VERSIONED_FILES)
    run(["git", "commit", "-m",
         f"chore(release): bump to v{new}\n\nCo-Authored-By: Claude Fable 5 <noreply@anthropic.com>"])
    ok("bump committed")


# ── Build ──────────────────────────────────────────────────────────────────

def _stage_plugin(dest: Path, ver: str):
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "data").mkdir(parents=True)
    (dest / "scripts").mkdir()
    for d in PLUGIN_DIRS:
        shutil.copytree(ROOT / d, dest / Path(d).name)
    for f in PLUGIN_FILES + PLUGIN_DOCS:
        shutil.copy2(ROOT / f, dest / Path(f).name)
    for f in PLUGIN_DATA:
        shutil.copy2(ROOT / f, dest / "data" / Path(f).name)
    for f in PLUGIN_SCRIPTS:
        shutil.copy2(ROOT / f, dest / "scripts" / Path(f).name)
    notes = ROOT / f"doc/RELEASE_NOTES_v{ver}.md"
    if notes.exists():
        shutil.copy2(notes, dest / notes.name)


def _zip_dir(folder: Path):
    # Not with_suffix(): version dots make it truncate "v2.8.0-lite" to "v2.8"
    zip_path = folder.parent / (folder.name + ".zip")
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(folder.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(ROOT))
    return zip_path


def build(ver):
    step(f"Building artifacts for v{ver}")
    artifacts = []

    lite = ROOT / f"hymnflow-v{ver}-lite"
    _stage_plugin(lite, ver)
    for f in LITE_EXTRAS:
        shutil.copy2(ROOT / f, lite / "data" / Path(f).name)
    artifacts.append(_zip_dir(lite))

    full = ROOT / f"hymnflow-v{ver}-full"
    _stage_plugin(full, ver)
    for f in BIBLES + HYMNS:
        shutil.copy2(ROOT / f, full / "data" / Path(f).name)
    artifacts.append(_zip_dir(full))

    data = ROOT / f"hymnflow-v{ver}-data"
    if data.exists():
        shutil.rmtree(data)
    (data / "data").mkdir(parents=True)
    for f in BIBLES + HYMNS:
        shutil.copy2(ROOT / f, data / "data" / Path(f).name)
    artifacts.append(_zip_dir(data))

    for a in artifacts:
        ok(f"{a.name}  ({a.stat().st_size / 1e6:.1f} MB)")
    return artifacts


def verify_artifacts(ver, artifacts):
    step("Verifying packaged contents")
    # Guard against verifying stale files from an earlier build
    expected = {f"hymnflow-v{ver}-{kind}.zip" for kind in ("lite", "full", "data")}
    produced = {a.name for a in artifacts}
    if produced != expected:
        die(f"built {sorted(produced)}, expected {sorted(expected)}")
    full = ROOT / f"hymnflow-v{ver}-full.zip"
    with zipfile.ZipFile(full) as z:
        names = z.namelist()
        html = z.read(f"hymnflow-v{ver}-full/obs-dock/index.html").decode("utf-8")
        if f"v={ver}" not in html:
            die(f"packaged index.html is not versioned v={ver} — build from a bumped tree")
        if not any(n.endswith(f"RELEASE_NOTES_v{ver}.md") for n in names):
            die("release notes missing from the full bundle")
        packaged_bibles = [n for n in names if "/data/bible-" in n]
        if len(packaged_bibles) < len(BIBLES):
            die(f"full bundle has {len(packaged_bibles)} bible files, expected ≥ {len(BIBLES)}")
    ok(f"full bundle: v={ver} refs, release notes, {len(packaged_bibles)} bibles")


# ── Tag & publish ──────────────────────────────────────────────────────────

def tag(ver):
    step(f"Tagging v{ver}")
    run(["git", "tag", "-a", f"v{ver}", "-m", f"Release v{ver} - HymnFlow OBS Plugin"])
    ok(f"tag v{ver} created")


def publish(ver, artifacts):
    step("Publishing")
    run(["git", "push", "origin", "master", f"v{ver}"])
    ok("pushed master + tag")

    title = release_title(ver)
    notes = str(ROOT / f"doc/RELEASE_NOTES_v{ver}.md")
    exists = run(["gh", "release", "view", f"v{ver}"], check=False).returncode == 0
    if exists:
        # Pre-created (e.g. via the web UI) — fix title/notes, add our assets
        run(["gh", "release", "edit", f"v{ver}", "--title", title,
             "--notes-file", notes, "--latest"])
        run(["gh", "release", "upload", f"v{ver}", *map(str, artifacts), "--clobber"])
        ok("existing release corrected: title/notes replaced, assets uploaded")
    else:
        run(["gh", "release", "create", f"v{ver}", *map(str, artifacts),
             "--title", title, "--notes-file", notes, "--latest"])
        ok("GitHub release created with all assets")
    url = run(["gh", "release", "view", f"v{ver}", "--json", "url", "-q", ".url"]).stdout.strip()
    print(f"\n🎉 Published: {url}")


def release_title(ver):
    """'HymnFlow vX — <headline>' taken from the release notes H1."""
    notes = (ROOT / f"doc/RELEASE_NOTES_v{ver}.md").read_text(encoding="utf-8")
    m = re.match(r"#\s*(.+)", notes)
    return m.group(1).strip() if m else f"HymnFlow v{ver}"


# ── Main ───────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser(description="HymnFlow release automation")
    ap.add_argument("version", nargs="?", help="explicit version (X.Y.Z)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--major", action="store_true")
    g.add_argument("--minor", action="store_true", help="default when no version given")
    g.add_argument("--patch", action="store_true")
    ap.add_argument("--publish", action="store_true",
                    help="push master + tag and create/fix the GitHub release")
    ap.add_argument("--rebuild", action="store_true",
                    help="rebuild artifacts for the current version; no bump/tag/publish")
    ap.add_argument("--yes", action="store_true", help="skip the confirmation prompt")
    ap.add_argument("--dry-run", action="store_true", help="print the plan and exit")
    args = ap.parse_args()

    cur = current_version()

    if args.rebuild:
        preflight(cur, publish=False, rebuild=True)
        artifacts = build(cur)
        verify_artifacts(cur, artifacts)
        print(f"\n✅ Rebuilt v{cur} artifacts (no bump, no tag).")
        return

    new = compute_version(args, cur)

    print(f"HymnFlow release: {cur} → {new}" + ("  [publish]" if args.publish else "  [local only]"))
    if args.dry_run:
        print("\nPlan: preflight → bump+commit → build 3 zips → verify → tag"
              + (" → push → GitHub release" if args.publish else "")
              + f"\nNeeds: doc/CHANGELOG.md '## [{new}]' section and doc/RELEASE_NOTES_v{new}.md")
        return

    preflight(new, args.publish, rebuild=False)

    if not args.yes:
        answer = input(f"\nProceed with v{new}{' and publish to GitHub' if args.publish else ''}? [y/N] ")
        if answer.strip().lower() not in ("y", "yes"):
            die("aborted by user")

    bump(cur, new)
    artifacts = build(new)
    verify_artifacts(new, artifacts)
    tag(new)

    if args.publish:
        publish(new, artifacts)
    else:
        print(f"\n✅ v{new} built and tagged locally. To publish:"
              f"\n   python scripts/release.py --rebuild   (if artifacts were cleaned)"
              f"\n   git push origin master v{new}"
              f"\n   gh release create v{new} hymnflow-v{new}-*.zip --title \"{release_title(new)}\" --notes-file doc/RELEASE_NOTES_v{new}.md --latest"
              f"\n…or rerun with --publish next time.")


if __name__ == "__main__":
    main()
